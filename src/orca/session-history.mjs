// Reads Orca's Agent Session History for the game: each session's token total, workspace, title
// and whether it still runs. Nothing else of a session is kept, and conversations are never read.
import { displayText } from '../domain/display-text.mjs'

export const SESSION_HISTORY_METHOD = 'agent.listSessions'
export const HISTORY_CAPABILITY = 'history:read'
/**
 * Sessions asked for per reading, newest first. Running sessions are among the newest, and a
 * finished one is read until it drops out of this window.
 */
const SESSIONS_PER_READING = 200
/** Same as a conversation title from Orca. */
const TITLE_LIMIT = 80
/** Session ids are generated by the agent CLIs; anything longer is not one. */
const SESSION_ID_LIMIT = 200
/** Errors that mean the person has not granted, or no longer grants, reading the history. */
const PERMISSION_CODES = new Set(['capability_denied', 'consent_required'])

/**
 * @typedef {import('../domain/game-sessions.mjs').HistorySession} HistorySession
 */

const isCount = (value) => typeof value === 'number' && Number.isFinite(value) && value >= 0
const timeOrNull = (value) => (isCount(value) ? value : null)
const textOrNull = (value) => (typeof value === 'string' && value !== '' ? value : null)

/**
 * The sessions of an `agent.listSessions` answer the game can use, with only the fields it needs.
 * Malformed rows are left out.
 *
 * @param {unknown} answer
 * @returns {{ sessions: HistorySession[], truncated: boolean }}
 */
export function normalizeSessions(answer) {
  const rows = Array.isArray(answer?.sessions) ? answer.sessions : []
  const sessions = []
  const seen = new Set()
  for (const row of rows) {
    const sessionId = textOrNull(row?.sessionId)
    if (!sessionId || sessionId.length > SESSION_ID_LIMIT || seen.has(sessionId) || !isCount(row.totalTokens)) continue
    seen.add(sessionId)
    sessions.push({
      sessionId,
      title: displayText(row.title, TITLE_LIMIT),
      workspaceId: textOrNull(row.workspaceId),
      totalTokens: row.totalTokens,
      createdAt: timeOrNull(row.createdAt),
      running: row.running === true
    })
  }
  return { sessions, truncated: answer?.truncated === true }
}

/**
 * Whether this Orca offers the history to the worker, and whether the person granted it.
 * `orca.grantedCapabilities` is fixed when the worker starts; an Orca without it is asked, and
 * a refusal then says so (see readSessionHistory).
 *
 * @param {{ host: { has?: (method: string) => boolean }, grantedCapabilities?: readonly string[] }} orca
 * @returns {{ supported: boolean, granted: boolean }}
 */
export function historyAccess(orca) {
  const supported = typeof orca.host?.has === 'function' && orca.host.has(SESSION_HISTORY_METHOD) === true
  const granted = Array.isArray(orca.grantedCapabilities) ? orca.grantedCapabilities.includes(HISTORY_CAPABILITY) : true
  return { supported, granted }
}

/**
 * Reads the history once.
 *
 * @param {{ host: { call: (method: string, params?: object) => Promise<unknown> } }} orca
 * @returns {Promise<{ ok: true, sessions: HistorySession[], truncated: boolean }
 *   | { ok: false, denied: boolean, message: string }>}
 */
export async function readSessionHistory(orca) {
  try {
    const answer = await orca.host.call(SESSION_HISTORY_METHOD, { limit: SESSIONS_PER_READING })
    return { ok: true, ...normalizeSessions(answer) }
  } catch (error) {
    return { ok: false, denied: PERMISSION_CODES.has(error?.code), message: `${error?.code ?? ''} ${error?.message ?? error}` }
  }
}

/**
 * Orca's workspaces with their folder, so a session's workspace can be found by folder when the
 * history names it in another form of id. Empty when the list cannot be read.
 *
 * @param {{ host: { call: (method: string, params?: object) => Promise<any> } }} orca
 * @returns {Promise<{ id: string, path: string, hostId: string | null }[]>}
 */
export async function readListedWorkspaces(orca) {
  try {
    const answer = await orca.host.call('workspace.list')
    const rows = Array.isArray(answer?.workspaces) ? answer.workspaces : []
    return rows
      .filter((row) => textOrNull(row?.id) && textOrNull(row?.path))
      .map((row) => ({ id: row.id, path: row.path, hostId: textOrNull(row.hostId) }))
  } catch {
    // Only a help for placing sessions; without it, ids the store knows still place them.
    return []
  }
}
