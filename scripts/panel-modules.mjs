// Writes ui/boot/panel-modules.js: every module the Orca panel loads, each after the ones it
// imports. Orca serves a panel about 32 files at a time and answers 503 to the rest, so the panel
// loads its modules one by one in this order (ui/boot/panel.js) instead of all at once.
// `npm run check` fails while the list differs from the imports; run `npm run sync-panel-modules`.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const BOOT = path.join(ROOT, 'ui', 'boot')
const ENTRY = path.join(BOOT, 'orca.js')
export const PANEL_MODULES_FILE = path.join(BOOT, 'panel-modules.js')

/** Relative imports of a module's source: `import … from`, `export … from` and bare `import`. */
const IMPORT = /(?:^|\n)\s*(?:import|export)\b[^'"]*?['"](\.{1,2}\/[^'"]+)['"]/g

/** Every module the entry reaches, each after its own imports, as paths relative to ui/boot/. */
export function panelModuleOrder() {
  const order = []
  const seen = new Set()
  const visit = (file) => {
    if (seen.has(file)) return
    seen.add(file)
    const source = fs.readFileSync(file, 'utf8')
    for (const match of source.matchAll(IMPORT)) visit(path.resolve(path.dirname(file), match[1]))
    order.push(file)
  }
  visit(ENTRY)
  return order.map((file) => {
    const relative = path.relative(BOOT, file).split(path.sep).join('/')
    return relative.startsWith('.') ? relative : `./${relative}`
  })
}

/** The generated module's text for an order. */
export function panelModulesSource(order = panelModuleOrder()) {
  const header = '// Generated by scripts/panel-modules.mjs from the imports: do not edit. Every module the Orca\n' +
    '// panel loads, each after the ones it imports, so panel.js can load them one at a time.\n'
  return `${header}export const PANEL_MODULES = [\n${order.map((item) => `  '${item}'`).join(',\n')}\n]\n`
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const order = panelModuleOrder()
  fs.writeFileSync(PANEL_MODULES_FILE, panelModulesSource(order))
  console.log(`sync-panel-modules: listed ${order.length} modules in ui/boot/panel-modules.js`)
}
